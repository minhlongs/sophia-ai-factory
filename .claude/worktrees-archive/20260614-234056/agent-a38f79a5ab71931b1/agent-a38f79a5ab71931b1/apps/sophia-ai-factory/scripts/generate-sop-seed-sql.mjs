#!/usr/bin/env node
/**
 * Generate SOP Seed SQL (0058-sop-seed-official.sql)
 *
 * Reads seed data from src/lib/sop/seeds/index.ts (via tsx/dynamic import)
 * and emits idempotent INSERT OR IGNORE statements for all 5 official SOPs.
 *
 * Usage: node scripts/generate-sop-seed-sql.mjs
 * Or via npm: npm run db:gen-sop-seed
 *
 * Idempotent: stable IDs derived from slug — re-running produces same SQL.
 */

import { createRequire } from 'node:module';
import { writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const appRoot = join(__dirname, '..');
const outputPath = join(appRoot, 'migrations', '0058-sop-seed-official.sql');

/** Escape single quotes for SQL string literals */
function sqlEsc(str) {
  return str.replace(/'/g, "''");
}

/** Convert slug to stable ID: sop_official_{slug_underscored} */
function slugToId(slug) {
  return 'sop_official_' + slug.replace(/-/g, '_');
}

/** Unix timestamp (seconds) for now */
function nowSec() {
  return Math.floor(Date.now() / 1000);
}

async function loadSeeds() {
  // Try tsx execution to load TypeScript seeds
  const seedsPath = join(appRoot, 'src', 'lib', 'sop', 'seeds', 'index.ts');

  if (!existsSync(seedsPath)) {
    throw new Error(`Seeds file not found: ${seedsPath}`);
  }

  // Use tsx to compile and run seeds extraction inline
  const extractScript = join(appRoot, 'scripts', '__sop-seeds-extract.mjs');
  const extractContent = `
import { register } from 'node:module';
import { pathToFileURL } from 'node:url';
register('tsx/esm', pathToFileURL('./'));

const { SOP_SEEDS } = await import(${JSON.stringify(pathToFileURL(seedsPath).href)});
process.stdout.write(JSON.stringify(SOP_SEEDS));
`;

  writeFileSync(extractScript, extractContent, 'utf8');

  try {
    const json = execSync(`node ${JSON.stringify(extractScript)}`, {
      cwd: appRoot,
      timeout: 30_000,
      encoding: 'utf8',
    });
    return JSON.parse(json);
  } finally {
    // Cleanup temp script
    try {
      const { unlinkSync } = await import('node:fs');
      unlinkSync(extractScript);
    } catch { /* ignore */ }
  }
}

function buildSql(seeds) {
  const ts = nowSec();
  const lines = [
    '-- SOP Official Seed Data (auto-generated by scripts/generate-sop-seed-sql.mjs)',
    '-- DO NOT EDIT MANUALLY — regenerate with: npm run db:gen-sop-seed',
    `-- Generated at: ${new Date().toISOString()}`,
    '',
  ];

  for (const seed of seeds) {
    const id = sqlEsc(slugToId(seed.slug));
    const slug = sqlEsc(seed.slug);
    const nameVi = sqlEsc(seed.nameVi);
    const nameEn = sqlEsc(seed.nameEn);
    const descVi = sqlEsc(seed.descVi);
    const descEn = sqlEsc(seed.descEn);
    const category = sqlEsc(seed.category);
    const agentsYaml = sqlEsc(seed.agentsYaml);
    const playbookMd = sqlEsc(seed.playbookMd);
    const outputSchema = sqlEsc(seed.outputSchema);
    const credits = seed.creditsPerRun;

    lines.push(
      `INSERT OR IGNORE INTO sop_templates (id, slug, name_vi, name_en, description_vi, description_en, category, agents_yaml, playbook_md, output_schema, credits_per_run, version, is_official, author_user_id, status, created_at, updated_at) VALUES ('${id}', '${slug}', '${nameVi}', '${nameEn}', '${descVi}', '${descEn}', '${category}', '${agentsYaml}', '${playbookMd}', '${outputSchema}', ${credits}, 1, 1, NULL, 'published', ${ts}, ${ts});`,
      '',
    );
  }

  return lines.join('\n');
}

async function main() {
  console.log('[gen-sop-seed] Loading seed modules...');

  let seeds;
  try {
    seeds = await loadSeeds();
  } catch (err) {
    // Fallback: inline seed data to avoid tsx dependency issues in some envs
    console.warn('[gen-sop-seed] tsx load failed, using inline fallback:', err.message);
    seeds = await loadSeedsInline();
  }

  if (!Array.isArray(seeds) || seeds.length === 0) {
    console.error('[gen-sop-seed] No seeds loaded — aborting');
    process.exit(1);
  }

  console.log(`[gen-sop-seed] Loaded ${seeds.length} seeds`);

  const sql = buildSql(seeds);
  writeFileSync(outputPath, sql, 'utf8');

  console.log(`[gen-sop-seed] Written: ${outputPath}`);
  console.log(`[gen-sop-seed] ${seeds.length} official SOPs seeded`);
}

