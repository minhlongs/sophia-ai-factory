/**
 * E2E API Endpoint Smoke Tests — No auth required for public checks.
 *
 * Run: npx playwright test tests/e2e/api-endpoints.spec.ts
 * Env: NEXT_PUBLIC_MOCK_AI_SERVICES=true
 *
 * Coverage:
 * - GET /api/health — 200 + status field
 * - GET /robots.txt — 200
 * - GET /sitemap.xml — 200 + XML content
 * - POST /api/admin/api-keys without auth — 401
 * - POST /api/v1/campaigns/create without auth — 401
 * - GET /api/v1/usage without auth — 401
 *
 * Uses Playwright `request` fixture for API testing (no browser).
 */

import { test, expect } from '@playwright/test';

test.describe('Public API smoke tests', () => {
  test('GET /api/health returns 200 with status field', async ({ request }) => {
    const response = await request.get('/api/health');
    // Accepts 200 (healthy/degraded) or 503 (unhealthy)
    expect([200, 503]).toContain(response.status());

    const body = await response.json();
    expect(body).toHaveProperty('status');
    expect(['healthy', 'degraded', 'unhealthy']).toContain(body.status);
  });

  test('GET /robots.txt returns 200', async ({ request }) => {
    const response = await request.get('/robots.txt');
    // robots.txt may be generated by Next.js or served statically
    expect([200, 404]).toContain(response.status());
    if (response.status() === 200) {
      const text = await response.text();
      expect(text.length).toBeGreaterThan(0);
    }
  });

  test('GET /sitemap.xml returns 200 with XML content type', async ({ request }) => {
    const response = await request.get('/sitemap.xml');
    // Sitemap may or may not be configured
    expect([200, 404]).toContain(response.status());
    if (response.status() === 200) {
      const contentType = response.headers()['content-type'] ?? '';
      // Should be XML
      expect(contentType).toMatch(/xml|text/i);
    }
  });
});

