/**
 * Environment Variable Sanitizer & Customer Export Generator
 * Layer: tree (Domain operations; imports only from @/seed)
 *
 * Ingests .env.example as canonical schema, masks sensitive secrets
 * with length indicators, preserves public configurations, and flags
 * missing mandatory production keys.
 *
 * @module tree/handover/env-export-generator
 */

import type { SanitizedEnvResult } from '@/seed/handover/handover-types';
import {
  PUBLIC_CONFIG_KEYS,
  MANDATORY_PRODUCTION_KEYS,
  isSensitiveKey,
  maskSecretValue,
} from './env-key-policy';

export {
  PUBLIC_CONFIG_KEYS,
  MANDATORY_PRODUCTION_KEYS,
  isSensitiveKey,
  maskSecretValue,
};

/**
 * Generates a sanitized .env.production bundle based on .env.example template
 * and current runtime environment variables.
 */
export function generateSanitizedEnvProduction(
  envExampleContent: string,
  currentEnv: Record<string, string | undefined> = {},
): SanitizedEnvResult {
  const lines = envExampleContent.split(/\r?\n/);
  const outputLines: string[] = [];
  const missingKeys: string[] = [];
  const warnings: string[] = [];

  let sectionCount = 0;
  let totalKeys = 0;

  outputLines.push('# ==============================================================================');
  outputLines.push('# SOPHIA AI FACTORY — SANITIZED CUSTOMER PRODUCTION ENVIRONMENT EXPORT');
  outputLines.push('# Generated by Phase 20 Automated Customer Handover Engine');
  outputLines.push(`# Exported At: ${new Date().toISOString()}`);
  outputLines.push('# NOTE: All cryptographic secrets and API keys are redacted with length markers.');
  outputLines.push('# ==============================================================================');
  outputLines.push('');

  for (const line of lines) {
    const trimmed = line.trim();

    // Preserve section comment headers
    if (trimmed.startsWith('#') || trimmed === '') {
      if (trimmed.startsWith('# ───') || trimmed.startsWith('# Phase')) {
        sectionCount++;
      }
      outputLines.push(line);
      continue;
    }

    // Process KEY=VALUE lines
    const eqIdx = line.indexOf('=');
    if (eqIdx === -1) {
      outputLines.push(line);
      continue;
    }

    const key = line.slice(0, eqIdx).trim();
    const defaultValue = line.slice(eqIdx + 1).trim();
    totalKeys++;

    const runtimeVal = currentEnv[key];
    const isMandatory = MANDATORY_PRODUCTION_KEYS.has(key);
    const isMissing = !runtimeVal && !defaultValue;

    if (isMandatory && isMissing) {
      missingKeys.push(key);
      const warnMsg = `MISSING MANDATORY CONFIGURATION KEY: ${key}`;
      warnings.push(warnMsg);
      outputLines.push(`# ⚠️ WARNING: ${warnMsg}`);
    }

    if (isSensitiveKey(key)) {
      const masked = maskSecretValue(key, runtimeVal || defaultValue);
      outputLines.push(`${key}=${masked}`);
    } else {
      // Public / safe configuration
      const effectiveVal = runtimeVal || defaultValue || '';
      outputLines.push(`${key}=${effectiveVal}`);
    }
  }

  return {
    sanitizedContent: outputLines.join('\n'),
    missingKeys,
    totalKeys,
    sectionCount: Math.max(sectionCount, 1),
    warnings,
  };
}
