import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  ARM_COMPARISON_SPECS,
  assertBlindPacketIsolation,
  buildBlindEvaluationPackets,
  installBenchmarkZeroNetworkGuard,
  runPairedFixtureBenchmark,
  verifyFrozenDataset,
  type ExperimentConfig,
} from '../index';

const EVAL_DIR = resolve(process.cwd(), 'eval/b4-first-value');

function loadConfigAndBriefs() {
  const datasetRaw = readFileSync(resolve(EVAL_DIR, 'dataset-v1.jsonl'), 'utf8');
  const manifestRaw = readFileSync(resolve(EVAL_DIR, 'dataset-manifest.json'), 'utf8');
  const { manifest, briefs } = verifyFrozenDataset(datasetRaw, manifestRaw);
  const config: ExperimentConfig = {
    configVersion: 'b4-exp-v1.0.0',
    datasetVersion: manifest.datasetVersion,
    datasetSha256: manifest.datasetSha256,
    rubricVersion: manifest.rubricVersion,
    rubricSha256: manifest.rubricSha256,
    mode: 'fixture_simulated',
    trialsPerBrief: 3,
    randomSeed: 'b4-seed-2026-11-23',
    plannedModelId: 'anthropic/claude-sonnet-4',
    plannedModelVersion: '2025-05-14',
    temperature: 0.3,
    maxOutputTokensBudget: 1200,
    targetDurationSec: 30,
  };
  return { briefs, config };
}

describe('B4 Paired Arms, Zero-Network Guard, and Blind Packet Isolation', () => {
  it('enforces zero-network guard and blocks any outbound fetch attempt', async () => {
    const guard = installBenchmarkZeroNetworkGuard();
    try {
      await expect(fetch('https://openrouter.ai/api/v1/chat/completions')).rejects.toThrow(
        /B4_ZERO_NETWORK_VIOLATION/,
      );
      expect(guard.blockedUrls).toEqual(['https://openrouter.ai/api/v1/chat/completions']);
    } finally {
      guard.restore();
    }
  });

  it('executes full 50x2x3=300 paired fixture trials with zero network calls and honest NOT_MEASURED telemetry', async () => {
    const { briefs, config } = loadConfigAndBriefs();
    const guard = installBenchmarkZeroNetworkGuard();
    try {
      const trials = await runPairedFixtureBenchmark(briefs, config);

      expect(guard.blockedUrls).toHaveLength(0);
      expect(trials).toHaveLength(300);

      const armA = trials.filter((t) => t.armId === 'arm_a_sophia_basic');
      const armB = trials.filter((t) => t.armId === 'arm_b_direct_model');
      expect(armA).toHaveLength(150);
      expect(armB).toHaveLength(150);
      expect(ARM_COMPARISON_SPECS.arm_a_sophia_basic.parityGuarantee).toContain('plannedModelId');
      expect(ARM_COMPARISON_SPECS.arm_b_direct_model.parityGuarantee).toContain('plannedModelId');

      for (const trial of trials) {
        expect(trial.executionMode).toBe('fixture_simulated');
        expect(trial.qualityStatus).toBe('QUALITY_NOT_MEASURED');
        expect(trial.telemetry.realPaidInferenceCostMicroUsd).toBe(0);
        expect(trial.telemetry.promptTokens.status).toBe('NOT_MEASURED');
        expect(trial.telemetry.completionTokens.status).toBe('NOT_MEASURED');
        expect(trial.telemetry.wallClockLatencyMs.status).toBe('NOT_MEASURED');
        expect(trial.telemetry.measuredInferenceCostMicroUsd.status).toBe('NOT_MEASURED');
      }
    } finally {
      guard.restore();
    }
  });

  it('refuses live_observed execution in B4.0 ZERO_PAID_INFERENCE runner', async () => {
    const { briefs, config } = loadConfigAndBriefs();
    await expect(
      runPairedFixtureBenchmark(briefs.slice(0, 1), { ...config, mode: 'live_observed' }),
    ).rejects.toThrow(/ZERO_PAID_INFERENCE/);
  });

  it('generates deterministic seeded blind packets with strict arm-label isolation', async () => {
    const { briefs, config } = loadConfigAndBriefs();
    const subset = briefs.slice(0, 5);
    const trials = await runPairedFixtureBenchmark(subset, { ...config, trialsPerBrief: 2 });

    const bundle1 = buildBlindEvaluationPackets(trials, subset, {
      seed: config.randomSeed,
      rubricVersion: config.rubricVersion,
    });
    const bundle2 = buildBlindEvaluationPackets(trials, subset, {
      seed: config.randomSeed,
      rubricVersion: config.rubricVersion,
    });
    const bundleDiffSeed = buildBlindEvaluationPackets(trials, subset, {
      seed: 'b4-different-seed-999',
      rubricVersion: config.rubricVersion,
    });

    expect(bundle1.reviewerPacket).toHaveLength(20);
    expect(bundle1.armKeyMap).toHaveLength(20);
    expect(bundle1.reviewerPacketSha256).toBe(bundle2.reviewerPacketSha256);
    expect(bundle1.armKeyMapSha256).toBe(bundle2.armKeyMapSha256);
    expect(bundle1.reviewerPacketSha256).not.toBe(bundleDiffSeed.reviewerPacketSha256);

    // Verify no arm identity leaked into reviewer packet
    expect(() => assertBlindPacketIsolation(bundle1.reviewerPacket)).not.toThrow();
    const leakyPacket = [
      { ...bundle1.reviewerPacket[0], renderedScript: 'Generated by arm_a_sophia_basic' },
    ];
    expect(() => assertBlindPacketIsolation(leakyPacket)).toThrow(/isolation violation/);

    // Duplicate trial rejection
    expect(() =>
      buildBlindEvaluationPackets([...trials, trials[0]], subset, {
        seed: config.randomSeed,
        rubricVersion: config.rubricVersion,
      }),
    ).toThrow(/Duplicate trialId/);
  });
});
