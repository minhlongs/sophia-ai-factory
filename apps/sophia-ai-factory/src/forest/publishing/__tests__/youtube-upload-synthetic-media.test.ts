/**
 * YouTube upload metadata — labelled-fixture tests
 *
 * Asserts the exact body sent to the YouTube Data API v3 resumable session,
 * which is where the `containsSyntheticMedia` disclosure either exists or does
 * not. No provider is contacted.
 *
 * @module forest/publishing/__tests__/youtube-upload-synthetic-media
 */

import { beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  recordSuccess: vi.fn(),
  recordFailure: vi.fn(),
  loggerInfo: vi.fn(),
}));

vi.mock('@/seed/security/circuit-breaker', () => ({
  recordSuccess: mocks.recordSuccess,
  recordFailure: mocks.recordFailure,
}));
vi.mock('@/seed/utils/logger-utility', () => ({
  logger: { info: mocks.loggerInfo, warn: vi.fn() },
}));

import { YT_UPLOAD_URL, performYouTubeUpload } from '../youtube-adapter-http';

const initResponse = () => new Response(null, {
  status: 200,
  headers: { Location: 'https://upload.googleapis.test/session-abc' },
});

const uploadResponse = () => new Response(JSON.stringify({ id: 'yt_video_42' }), { status: 200 });

const videoResponse = () => new Response(new Uint8Array([4, 5, 6]), { status: 200 });

const initBody = (fetchMock: ReturnType<typeof vi.fn>): { status: { containsSyntheticMedia?: boolean; privacyStatus?: string } } => {
  const init = fetchMock.mock.calls[0]?.[1] as RequestInit;
  return JSON.parse(String(init.body)) as { status: { containsSyntheticMedia?: boolean; privacyStatus?: string } };
};

describe('performYouTubeUpload', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('sends containsSyntheticMedia true in the uploaded status metadata', async () => {
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(initResponse())
      .mockResolvedValueOnce(videoResponse())
      .mockResolvedValueOnce(uploadResponse());
    vi.stubGlobal('fetch', fetchMock);

    await performYouTubeUpload('fixture_token', {
      videoUrl: 'https://cdn.example.test/video.mp4',
      title: 'A generated video',
      description: 'Generated by Sophia',
    });

    expect(fetchMock.mock.calls[0]?.[0]).toBe(`${YT_UPLOAD_URL}?uploadType=resumable&part=snippet,status`);
    expect(initBody(fetchMock).status.containsSyntheticMedia).toBe(true);
    expect(mocks.recordSuccess).toHaveBeenCalledWith('youtube');
  });

  it('keeps the disclosure true when the caller passes privacy private', async () => {
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(initResponse())
      .mockResolvedValueOnce(videoResponse())
      .mockResolvedValueOnce(uploadResponse());
    vi.stubGlobal('fetch', fetchMock);

    await performYouTubeUpload('fixture_token', {
      videoUrl: 'https://cdn.example.test/video.mp4',
      title: 'A generated video',
      description: 'Generated by Sophia',
      privacy: 'private',
    });

    expect(initBody(fetchMock).status.containsSyntheticMedia).toBe(true);
    expect(initBody(fetchMock).status.privacyStatus).toBe('private');
  });

  it('honours an explicit opt-out of the disclosure', async () => {
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(initResponse())
      .mockResolvedValueOnce(videoResponse())
      .mockResolvedValueOnce(uploadResponse());
    vi.stubGlobal('fetch', fetchMock);

    await performYouTubeUpload('fixture_token', {
      videoUrl: 'https://cdn.example.test/video.mp4',
      title: 'A human-captured clip',
      description: 'Not synthetic',
      containsSyntheticMedia: false,
    });

    expect(initBody(fetchMock).status.containsSyntheticMedia).toBe(false);
  });

  it('refuses the upload entirely when the provenance review leaves a claim unresolved', async () => {
    const fetchMock = vi.fn();
    vi.stubGlobal('fetch', fetchMock);

    await expect(performYouTubeUpload('fixture_token', {
      videoUrl: 'https://cdn.example.test/video.mp4',
      title: 'A generated video',
      description: 'Generated by Sophia',
      provenance: {
        sources: [{ status: 'verified', id: 'src_1', url: 'https://example.test/a' }],
        claims: [{
          id: 'claim_1', text: 'An unsupported claim', riskLevel: 'high',
          sourceIds: [], status: 'unsupported',
        }],
      },
    })).rejects.toThrow(/PROVENANCE_BLOCKED/);

    expect(fetchMock).not.toHaveBeenCalled();
    expect(mocks.recordFailure).not.toHaveBeenCalled();
  });

  it('uploads when every provenance claim is supported by a verified source', async () => {
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(initResponse())
      .mockResolvedValueOnce(videoResponse())
      .mockResolvedValueOnce(uploadResponse());
    vi.stubGlobal('fetch', fetchMock);

    await performYouTubeUpload('fixture_token', {
      videoUrl: 'https://cdn.example.test/video.mp4',
      title: 'A generated video',
      description: 'Generated by Sophia',
      provenance: {
        sources: [{ status: 'verified', id: 'src_1', url: 'https://example.test/a' }],
        claims: [{
          id: 'claim_1', text: 'A supported claim', riskLevel: 'standard',
          sourceIds: ['src_1'], status: 'supported',
        }],
      },
    });

    expect(initBody(fetchMock).status.containsSyntheticMedia).toBe(true);
    expect(mocks.recordSuccess).toHaveBeenCalledWith('youtube');
  });
});
